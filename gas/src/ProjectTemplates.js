// 參考工作項目的版本：內容有變動時加 1，下一次請求會自動補進範本表（只補缺的，不動主管改過的）。
const TEMPLATE_SEED_VERSION_ = '3';

/** 寫入基本事項與各類型參考工作項目；已存在（同分類＋項目）的略過，可重複執行。回傳新增筆數。 */
function seedTypeTemplates_(actor) {
  const repo = repo_('task_templates');
  const existing = {};
  const add = t => { existing[normName_(t.category + '|' + t.title)] = true; };
  repo.findAll().forEach(add);
  const rows = [];
  BASIC_REFERENCE_TASKS_.forEach(([category, title, offset, priority, role, done, tip, types], i) => {
    if (existing[normName_(category + '|' + title)]) return;
    add({ category, title });
    rows.push({ project_types: types ? types.join('、') : null, category, title, offset_days: offset, priority, role,
      done_criteria: done, tip, sort: 100 + i });
  });
  Object.keys(TYPE_REFERENCE_TASKS_).forEach(type => TYPE_REFERENCE_TASKS_[type].forEach(([category, title, offset, priority, role], i) => {
    // 各類型的項目可能同名（例如兩種類型都有「講師邀約」），同類型內才算重複
    const key = normName_(type + '|' + category + '|' + title);
    if (existing[key] || repo.findAll().some(t => t.project_types === type && normName_(t.category + '|' + t.title) === normName_(category + '|' + title))) return;
    existing[key] = true;
    rows.push({ project_types: type, category, title, offset_days: offset, priority, role, sort: 1000 + i });
  }));
  if (rows.length) repo.insertMany(rows, actor || 'system');
  return rows.length;
}

/** 移除上一版自動加入、已被取代的範本：只動系統建立且沒人改過的。 */
function retireOldTemplates_() {
  const repo = repo_('task_templates');
  const retired = {};
  RETIRED_TEMPLATES_.forEach(k => { retired[normName_(k)] = true; });
  const keyOf = t => normName_((t.project_types && templateTypes_(t).length === 1 && TYPE_REFERENCE_TASKS_[t.project_types] ? t.project_types + '|' : '') + t.category + '|' + t.title);
  let n = 0;
  repo.findAll().filter(t => t.created_by === 'system' && t.updated_by === 'system' && retired[keyOf(t)]).forEach(t => {
    repo.markDeleted(repo.readForWrite(t.id), 'system');
    n++;
  });
  return n;
}
