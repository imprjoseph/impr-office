/**
 * 各活動類型的參考工作項目。新增專案時：通用範本（project_types 空白，即追蹤表的 T-60 範本）＋該類型的參考項目。
 * 這裡只放該類型特有的工作，合約、總時程、結案這類共通工作由通用範本負責，避免重複。
 * 第一次升級時自動寫進工作範本（seedTypeTemplates_）；之後由主管在「系統設定 → 工作範本」增修，以範本表為準。
 *
 * 格式：[工作分類, 工作項目, 距活動日天數（T-30 填 -30）, 重要性, 建議負責角色]
 */
const PROJECT_TYPES = ['論壇', '研討會', '記者會', '展覽', '典禮', '訪查', '媒體宣傳', '教育訓練', '尾牙', '其他'];
// 舊名稱自動換成新名稱
const PROJECT_TYPE_ALIASES_ = { '頒獎典禮': '典禮' };

function normalizeProjectType_(v) {
  if (v === null || v === undefined || v === '') return v;
  const t = PROJECT_TYPE_ALIASES_[String(v).trim()] || String(v).trim();
  if (PROJECT_TYPES.indexOf(t) === -1) throw new AppError(ERROR_CODES.VALIDATION, '活動類型只能是：' + PROJECT_TYPES.join('、'));
  return t;
}

/** 範本的適用類型（逗號、頓號分隔）；空白代表所有類型。 */
function templateTypes_(t) {
  return String(t.project_types || '').split(/[,、，\s]+/).map(x => PROJECT_TYPE_ALIASES_[x] || x).filter(Boolean);
}

function templateAppliesTo_(t, projectType) {
  const types = templateTypes_(t);
  return !types.length || (!!projectType && types.indexOf(projectType) !== -1);
}

